day = int(input("Enter the day number :"))

match day:
    case 1:
        print("This is sunday")
    case 2:
        print("This is monday")
    case 3:
        print("This is tuesday")
    case 4:
        print("This is wednesday")
    case 5:
        print("This is thursday")
    case 6:
        print("This is friday")
    case 7:
        print("This is saturday")